export type Platform =
  | 'youtube'
  | 'tiktok'
  | 'instagram'
  | 'facebook'
  | 'dailymotion'
  | 'twitter'
  | 'twitch'
  | 'vimeo'
  | 'unknown';

export type CookiesBrowser =
  | 'firefox'
  | 'chrome'
  | 'chromium'
  | 'safari'
  | 'brave'
  | 'edge'
  | 'opera'
  | 'vivaldi'
  | null;

/** Ce que l'utilisateur a choisi pour les cookies : `auto` (le navigateur détecté, pour les
 * sites qui exigent une session), `none` (jamais), ou un navigateur précis. */
export type CookiesChoice = 'auto' | 'none' | NonNullable<CookiesBrowser>;

export type Quality = 'best' | '1080p' | '720p' | '480p';

export type DownloadStatus =
  | 'idle'
  | 'downloading'
  | 'complete'
  | 'error'
  | 'cancelled';

export type UrlKind = 'single' | 'playlist';

// Shapes of what the Rust backend sends. Generated by `cargo test` (ts-rs) from the Rust
// structs, so a field renamed on one side fails to compile on the other.
export type { VideoInfo } from './generated/VideoInfo';
export type { PlaylistEntry } from './generated/PlaylistEntry';
export type { PlaylistInfo } from './generated/PlaylistInfo';
export type { DownloadProgress } from './generated/DownloadProgress';
export type { DownloadComplete } from './generated/DownloadComplete';
export type { DownloadError } from './generated/DownloadError';
export type { DependencyStatus } from './generated/DependencyStatus';

export interface HistoryEntry {
  id: string;
  url: string;
  title: string;
  thumbnail: string;
  platform: Platform;
  filepath: string;
  downloaded_at: number;
  quality: Quality;
}

export interface QueueItem {
  id: string;
  url: string;
  outputDir: string;
  quality: Quality;
  audioOnly: boolean;
  playlistEnd: number | null;
  cookiesBrowser: CookiesBrowser;
  /** Titre connu avant le téléchargement (aperçu d'une playlist), pour l'historique. */
  title?: string;
  status: 'pending' | 'downloading' | 'done' | 'error';
  error?: string;
}
